// Finds every colocated `app/**/metadata.ts` and writes `generated/og-pages.ts`, a static import map
// keyed by public pathname. `app/og/[...path]/route.tsx` prerenders one OG image per entry.
//
// Usage: node scripts/generate-og-map.mjs [--watch]
import { existsSync, readdirSync, readFileSync, watch, writeFileSync } from "node:fs";
import { basename, dirname, join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const appDir = join(root, "app");
const outFile = join(root, "generated", "og-pages.ts");

function routePath(dir) {
  const segments = relative(appDir, dir).split(sep).filter(Boolean);
  const path = [];
  for (const segment of segments) {
    if (segment.startsWith("(") && segment.endsWith(")")) continue;
    if (/^[[@_]/.test(segment)) {
      throw new Error(
        `${relative(root, dir)}/metadata.ts: metadata.ts is only for static routes. ` +
          `Dynamic routes get OG images from an adapter in lib/og/entries.ts.`,
      );
    }
    path.push(segment);
  }
  return `/${path.join("/")}`;
}

function generate() {
  const pages = new Map();
  for (const file of readdirSync(appDir, { recursive: true })) {
    if (basename(file) !== "metadata.ts") continue;
    const dir = dirname(join(appDir, file));
    const path = routePath(dir);
    const existing = pages.get(path);
    if (existing) {
      throw new Error(`Duplicate OG page path ${path}: ${existing} and ${relative(root, dir)}`);
    }
    pages.set(path, relative(root, dir));
  }

  const entries = [...pages].sort(([a], [b]) => (a < b ? -1 : 1));
  const source = [
    "// Generated by scripts/generate-og-map.mjs. Do not edit.",
    'import type { PageMetadataInput } from "@/lib/page-metadata";',
    ...entries.map(
      ([, dir], i) => `import page${i} from "../${dir.split(sep).join("/")}/metadata";`,
    ),
    "",
    "export const ogPages: Record<string, PageMetadataInput> = {",
    ...entries.map(([path], i) => `  ${JSON.stringify(path)}: page${i},`),
    "};",
    "",
  ].join("\n");

  // Only write on change so `next dev` doesn't recompile on every run.
  if (!existsSync(outFile) || readFileSync(outFile, "utf8") !== source) {
    writeFileSync(outFile, source);
    console.log(`og-map: wrote ${entries.length} pages to ${relative(root, outFile)}`);
  }
}

generate();

if (process.argv.includes("--watch")) {
  let timer;
  watch(appDir, { recursive: true }, (_event, file) => {
    if (!file || basename(file) !== "metadata.ts") return;
    clearTimeout(timer);
    timer = setTimeout(() => {
      try {
        generate();
      } catch (error) {
        console.error(`og-map: ${error.message}`);
      }
    }, 100);
  });
  // Runs in the background next to `next dev`; exit once that shell is gone.
  const parent = process.ppid;
  setInterval(() => process.ppid !== parent && process.exit(0), 1000);
}
