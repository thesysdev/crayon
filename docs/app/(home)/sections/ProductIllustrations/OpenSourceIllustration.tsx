"use client";

import { createLibrary, defineComponent, Renderer } from "@openuidev/react-lang";
import { z } from "zod/v4";
import styles from "./OpenSourceIllustration.module.css";

// A small custom library, as consumers register with OpenUI. The exact response
// below drives both the rendered preview and its code panel: they cannot drift.
const Stack = defineComponent({
  name: "Stack",
  description: "Arrange children vertically or in a row.",
  props: z.object({
    children: z.array(z.any()),
    direction: z.enum(["column", "row"]).default("column"),
  }),
  component: ({ props, renderNode }) => (
    <div className={props.direction === "row" ? styles.row : styles.stack}>
      {renderNode(props.children)}
    </div>
  ),
});
const Hero = defineComponent({
  name: "Hero",
  description: "A trip heading over the library's Japan cover photograph.",
  props: z.object({ title: z.string(), description: z.string() }),
  component: ({ props }) => (
    <div className={styles.hero}>
      <strong>{props.title}</strong>
      <span>{props.description}</span>
    </div>
  ),
});
const Metric = defineComponent({
  name: "Metric",
  description: "A trip fact with its label, supporting text, value, and suffix.",
  props: z.object({ label: z.string(), detail: z.string(), value: z.string(), suffix: z.string() }),
  component: ({ props }) => (
    <div className={styles.metric}>
      <div>
        <strong>{props.label}</strong>
        <span>{props.detail}</span>
      </div>
      <div>
        <strong>{props.value}</strong>
        <span>{props.suffix}</span>
      </div>
    </div>
  ),
});
const photos = [
  "https://images.unsplash.com/photo-1540959733332-eab4deabeeaf?w=600&q=80&auto=format&fit=crop",
  "https://images.unsplash.com/photo-1542051841857-5f90071e7989?w=600&q=80&auto=format&fit=crop",
  "https://images.unsplash.com/photo-1493976040374-85c8e12f0c0e?w=600&q=80&auto=format&fit=crop",
];
const Day = defineComponent({
  name: "Day",
  description: "A day of the trip, illustrated with the library's Japan photography.",
  props: z.object({ number: z.number(), title: z.string(), description: z.string() }),
  component: ({ props }) => (
    <div className={styles.day}>
      {/* Decorative photography is selected by this custom component, not generated by the model. */}
      <img src={photos[props.number - 1]} alt="" />
      <span className={styles.dayNumber}>Day {props.number}</span>
      <strong>{props.title}</strong>
      <p>{props.description}</p>
    </div>
  ),
});
const library = createLibrary({ root: "Stack", components: [Stack, Hero, Metric, Day] });
export const tripResponse = `root = Stack([hero, summary, days])
hero = Hero("Tokyo Trip Itinerary",
  "7 days grouped by neighborhood")
summary = Stack([tripLength, base], "row")
tripLength = Metric("Trip length", "Tokyo plan",
  "7", "days")
base = Metric("Best base", "Easy transit",
  "Ginza", "or Shinjuku")
days = Stack([day1, day2, day3], "row")
day1 = Day(1, "Shinjuku arrival",
  "Easy first day to reset after landing")
day2 = Day(2, "Harajuku + Shibuya",
  "Vibrant culture and iconic sights")
day3 = Day(3, "Asakusa + Ueno",
  "Immerse in traditional Tokyo")`;

export function OpenSourceIllustration() {
  return (
    <div className={styles.art}>
      <div className={styles.preview}>
        <p className={styles.question}>
          I'm planning a trip to Japan. Can you create an itinerary for me?
        </p>
        <Renderer library={library} response={tripResponse} isStreaming={false} />
      </div>
      <pre className={styles.code} aria-label="OpenUI Lang rendered in the trip preview">
        <code>{tripResponse}</code>
      </pre>
    </div>
  );
}
