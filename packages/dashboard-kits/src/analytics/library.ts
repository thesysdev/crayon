// The product analytics kit's library: the dashboard base, the shared analytics
// blocks, and eight product components. `npm run generate` writes its spec.
export function createAnalyticsLibrary(base: Library): Library {
  return createKitLibrary(base, {
    group: {
      name: "Product analytics",
      notes: [
        'Lead every dashboard with one HeroMetric(kpis.hero, kpis.heroTrend, kpis.metrics, $metric) in a LargeCard; put the supporting KpiStrip(kpis.metrics, $metric) in its own LargeCard row, with RuleChips(kpis.rules). The shared $metric (declare $metric = "") makes each KPI tile a tab that shows its metric in the hero chart.',
        "Charts: TrendChart for anything over time, ColumnChart for counts per period or stacked composition (negative values draw below the line), BarList for ranked categories, ShareBar for part-to-whole. Prefer them over LineChart, AreaChart, BarChart, and PieChart.",
        "Say how users were counted: put a tool's rule in the card subtitle, and DataStatus(status.items) under the hero.",
        "To compare plans' retention, use TrendChart with get_retention_curves. FeatureAdoption is the ranked list for a MediumCard; EngagementMatrix needs a LargeCard.",
        "Put a DashboardCardHeader before each of these components.",
      ],
    },
    components: [
      { component: HeroMetric, slots: ["LargeCard"] },
      { component: TrendChart, slots: ["MediumCard", "LargeCard"] },
      { component: ColumnChart, slots: ["MediumCard", "LargeCard"] },
      { component: BarList, slots: ["MediumCard", "LargeCard"] },
      { component: ShareBar, slots: ["MediumCard", "LargeCard"] },
      { component: KpiStrip, slots: ["LargeCard"] },
      { component: RuleChips, slots: ["LargeCard", "MediumCard"] },
      { component: DataStatus, slots: ["LargeCard"] },
      { component: GoalPace, slots: ["MediumCard", "LargeCard"] },
      { component: Tracker, slots: ["MediumCard", "LargeCard"] },
      { component: InsightList, slots: ["MediumCard", "LargeCard"] },
      { component: DriverCards, slots: ["MediumCard", "LargeCard"] },
      { component: VarianceWalk, slots: ["LargeCard", "MediumCard"] },
      { component: ConversionFunnel, slots: ["MediumCard", "LargeCard"] },
      { component: CohortGrid, slots: ["LargeCard"] },
      { component: LifecycleChart, slots: ["LargeCard"] },
      { component: LifecycleFlow, slots: ["LargeCard"] },
      { component: ReleaseImpact, slots: ["LargeCard", "MediumCard"] },
      { component: PowerUserCurve, slots: ["MediumCard", "LargeCard"] },
      { component: EngagementMatrix, slots: ["LargeCard"] },
      { component: FeatureAdoption, slots: ["MediumCard", "LargeCard"] },
      { component: ActivityHeatmap, slots: ["LargeCard"] },
      { component: EventTable, slots: ["LargeCard"] },
      { component: UserPaths, slots: ["MediumCard", "LargeCard"] },
      { component: ExperimentResults, slots: ["LargeCard"] },
      { component: ActionCards, slots: ["LargeCard", "MediumCard"] },
      { component: FeatureValue, slots: ["LargeCard"] },
      { component: PaywallMatrix, slots: ["LargeCard"] },
      { component: CommitPacing, slots: ["LargeCard"] },
      { component: WeeklyReview, slots: ["LargeCard"] },
      { component: AccountHealth, slots: ["LargeCard"] },
      { component: ActivationMoments, slots: ["LargeCard"] },
    ],
  });
}
