// The e-commerce kit's library: the dashboard base, the shared analytics
// blocks, and six store components. `npm run generate` writes its spec.
export function createEcommerceLibrary(base: Library): Library {
  return createKitLibrary(base, {
    group: {
      name: "E-commerce",
      notes: [
        'Lead every dashboard with one HeroMetric(kpis.hero, kpis.heroTrend, kpis.metrics, $metric) in a LargeCard; put the supporting KpiStrip(kpis.metrics, $metric) in its own LargeCard row, with RuleChips(kpis.rules) under it. The shared $metric (declare $metric = "") makes each KPI tile a tab that shows its metric in the hero chart.',
        "Charts: TrendChart for anything over time, ColumnChart for counts per period or stacked composition (negative values draw below the line), BarList for ranked categories, ShareBar for part-to-whole. Prefer them over LineChart, AreaChart, BarChart, and PieChart.",
        'Why questions: why = Query("explain_change", {metric: "contribution_profit", range: $range, compare: $compare}, {...}) then DriverCards(why) and VarianceWalk(why.walk, why.comparisonLabel, why.format).',
        'Breakdowns whose items carry keys (sales by channel, device, or category) can filter the dashboard: pass the matching filter $binding last, e.g. ShareBar(byChannel.items, "currency", $channel).',
        "Put a DashboardCardHeader before each of these components.",
      ],
    },
    components: [
      { component: HeroMetric, slots: ["LargeCard"] },
      { component: TrendChart, slots: ["MediumCard", "LargeCard"] },
      { component: ColumnChart, slots: ["MediumCard", "LargeCard"] },
      { component: BarList, slots: ["MediumCard", "LargeCard"] },
      { component: ShareBar, slots: ["MediumCard", "LargeCard"] },
      { component: KpiStrip, slots: ["LargeCard"] },
      { component: GoalPace, slots: ["MediumCard", "LargeCard"] },
      { component: BulletList, slots: ["MediumCard", "LargeCard"] },
      { component: Tracker, slots: ["MediumCard", "LargeCard"] },
      { component: InsightList, slots: ["MediumCard", "LargeCard"] },
      { component: DriverCards, slots: ["MediumCard", "LargeCard"] },
      { component: VarianceWalk, slots: ["LargeCard", "MediumCard"] },
      { component: ConversionFunnel, slots: ["MediumCard", "LargeCard"] },
      { component: CohortGrid, slots: ["LargeCard"] },
      { component: ProfitWaterfall, slots: ["LargeCard", "MediumCard"] },
      { component: MoneyBreakdown, slots: ["MediumCard", "LargeCard"] },
      { component: ChannelPerformance, slots: ["LargeCard"] },
      { component: CreativeLeaderboard, slots: ["LargeCard"] },
      { component: ActionCards, slots: ["LargeCard", "MediumCard"] },
      { component: ReconciliationCard, slots: ["MediumCard", "LargeCard"] },
      { component: RuleChips, slots: ["LargeCard", "MediumCard"] },
      { component: CustomerSegments, slots: ["LargeCard"] },
      { component: SegmentFlow, slots: ["LargeCard"] },
      { component: ProductPerformance, slots: ["LargeCard"] },
      { component: ProductLeaderboard, slots: ["MediumCard", "LargeCard"] },
      { component: ProductQuadrant, slots: ["LargeCard"] },
      { component: InventoryAlerts, slots: ["MediumCard", "LargeCard"] },
      { component: ExchangeMatrix, slots: ["MediumCard", "LargeCard"] },
    ],
  });
}
