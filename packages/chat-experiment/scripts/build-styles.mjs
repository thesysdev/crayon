// Generates src/styles/_components.scss: a single partial that `@use`s every
// co-located component .scss so they all get bundled into the compiled
// charts.css. Run before `sass src/styles/index.scss dist/charts.css`.
import { readdirSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";

const SRC = "src";
const OUT = "src/styles/_components.scss";
const SKIP = new Set(["index.scss", "tokens.scss", "chart-vars.scss", "_components.scss"]);

function walk(dir) {
  const out = [];
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) {
      out.push(...walk(p));
    } else if (name.endsWith(".scss") && !SKIP.has(name)) {
      out.push(p);
    }
  }
  return out;
}

const files = walk(SRC).sort();
const lines = files.map((p) => {
  const rel = relative("src/styles", p).replace(/\\/g, "/").replace(/\.scss$/, "");
  return `@use "${rel}" as *;`;
});

writeFileSync(OUT, `// AUTO-GENERATED by scripts/build-styles.mjs — do not edit.\n${lines.join("\n")}\n`);
console.log(`build-styles: wrote ${files.length} component style import(s) to ${OUT}`);
